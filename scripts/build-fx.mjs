#!/usr/bin/env node
/**
 * Turns the animation lab's entrances and exits into one ES module.
 *
 *   node scripts/build-fx.mjs           writes src/fx/generated/labFx.js
 *   node scripts/build-fx.mjs --check   exits 1 if that file is out of date
 *
 * The lab files in src/fx/lab/ are classic scripts: the kit declares its rig at
 * the top level, the effects read it as globals, and each effect hands itself
 * to a global registerFx(). An extension can't load scripts like that (MV3 has
 * no eval and no remote code), so this pastes them, unchanged, into one
 * function body. The kit's top-level names become that function's locals, and
 * `window` inside it is a plain object, so nothing lands on the page's window.
 * The result is static code that Vite bundles like any other module.
 *
 * Order matters and matches the lab pages: retro, rig, the x family's kit,
 * then the effects. Each effect gets its own block so their helpers never meet.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lab = resolve(root, 'src/fx/lab');
const out = resolve(root, 'src/fx/generated/labFx.js');

const KIT = ['retro.js', 'clippee-rig.js', 'xkit.js'];
const FX = ['r1', 'r4', 'r5', 'p1', 'p2', 'p4', 'c1', 'c4', 'x1', 'x2', 'x3', 'x4'];

const read = (path) => readFileSync(resolve(lab, path), 'utf8').replace(/\s+$/, '');

const parts = [
  '// Generated by scripts/build-fx.mjs from src/fx/lab/. Edit those, then run `npm run fx`.',
  '/* eslint-disable */',
  '',
  'export function createLabFx() {',
  '  const window = {};',
  '  const FX = {};',
  '  const registerFx = (def) => { FX[def.id] = def; return def; };',
  '  window.registerFx = registerFx;',
  '',
  `// ---- kit/${KIT[0]}`,
  read(`kit/${KIT[0]}`),
  'const retro = window.retro, retroRender = window.retroRender;',
  '',
  `// ---- kit/${KIT[1]}`,
  read(`kit/${KIT[1]}`),
  '',
  `// ---- kit/${KIT[2]}`,
  read(`kit/${KIT[2]}`),
  '',
  ...FX.flatMap((id) => [`// ---- fx/${id}.js`, '{', read(`fx/${id}.js`), '}', '']),
  '  return FX;',
  '}',
  '',
];
const text = parts.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== text) {
    console.error('src/fx/generated/labFx.js is out of date. Run `npm run fx`.');
    process.exit(1);
  }
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out.slice(root.length + 1)}: ${FX.length} effects`);
}
